#!/usr/bin/env python3
"""Package unmodified Fast64 model exports and describe their ROM ranges."""

import argparse
from pathlib import Path
import re


def model_name(export):
    relative = export.parent.relative_to(Path("assets/models"))
    if relative == Path("."):
        raise ValueError("each model.inc.c must be in its own assets/models subfolder")
    name = re.sub(r"[^A-Za-z0-9_]", "_", relative.as_posix())
    if name[0].isdigit():
        name = "_" + name
    return name


def generate(kind, exports):
    lines = ["/* Generated by tools/dma_model_assets.py. */"]
    if kind == "source":
        if len(exports) != 1:
            raise ValueError("source generation requires exactly one export")
        lines += [
            '#include "macros.h"',
            '#include "types.h"',
            '#include <ultra64.h>',
            '#include "sm64.h"',
            '#include "make_const_nonconst.h"',
        ]
        header = exports[0].parent / "header.h"
        if header.is_file():
            lines.append('#include "{}"'.format(header.as_posix()))
        lines.append('#include "{}"'.format(exports[0].as_posix()))
        return "\n".join(lines) + "\n"

    seen = set()
    if kind == "header":
        lines += ["#ifndef DMA_MODEL_ASSETS_H", "#define DMA_MODEL_ASSETS_H"]
    for export in exports:
        name = model_name(export)
        if name in seen:
            raise ValueError("duplicate model identifier: " + name)
        seen.add(name)
        prefix = "_dmaModel_" + name
        if kind == "header":
            header = export.parent / "header.h"
            if header.is_file():
                lines.append('#include "{}"'.format(header.as_posix()))
            for suffix in ("Start", "RomStart", "RomEnd"):
                lines.append("extern u8 {}{}[];".format(prefix, suffix))
        else:
            obj = (export.parent / "streamed_model.o").as_posix()
            lines += [
                ". = ALIGN(0x10);",
                "{}Start = .;".format(prefix),
                "{}RomStart = ABSOLUTE(LOADADDR(.dma_models) + (. - ADDR(.dma_models)));".format(prefix),
                "KEEP(BUILD_DIR/{}(.data* .rodata*));".format(obj),
                ". = ALIGN(0x10);",
                "{}RomEnd = ABSOLUTE(LOADADDR(.dma_models) + (. - ADDR(.dma_models)));".format(prefix),
            ]
    if kind == "header":
        lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kind", choices=("source", "header", "linker"))
    parser.add_argument("output", type=Path)
    parser.add_argument("exports", nargs="*", type=Path)
    args = parser.parse_args()
    try:
        contents = generate(args.kind, sorted(args.exports))
    except ValueError as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.is_file() or args.output.read_text() != contents:
        args.output.write_text(contents)


if __name__ == "__main__":
    main()
